n_bins = 20
ax2.hist(flare_phases, bins=n_bins, range=(0, 1), color='#ff7f0e', edgecolor='black', alpha=0.7)
ax2.axhline(len(flare_phases)/n_bins, color='black', linestyle=':', label='Uniform Background Expectation')
