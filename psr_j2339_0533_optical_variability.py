fig2, axes2 = plt.subplots(2, 1, figsize=(10, 8), dpi=300, sharex=True)

# Panel A
axes2[0].scatter(phase[safe_mask], frac_residuals_masked, color='gray', alpha=0.15, s=2, rasterized=True, label='Masked Residuals (Off-Minimum)')
