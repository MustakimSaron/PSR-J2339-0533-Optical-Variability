ax0.set_ylabel(r'Normalized Flux ($F / \langle F \rangle$)', fontweight='bold')
ax0.set_title(r'(a) Normalized Optical Light Curve of PSR J2339-0533 ($P_{\mathrm{orb}} = 4.63$ hr)', fontweight='bold', loc='left')
